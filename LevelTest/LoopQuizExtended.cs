        /// </summary>
        private static bool TryReadInt(string prompt, out int value, int min = int.MinValue, int max = int.MaxValue)
        {
            Console.Write(prompt);
            if (int.TryParse(Console.ReadLine(), out value) && value >= min && value <= max)
                return true;

            string range =
                (min == int.MinValue && max == int.MaxValue) ? "정수" :
                (min == int.MinValue) ? $"{max} 이하의 정수" :
                (max == int.MaxValue) ? $"{min} 이상의 정수" :
                                        $"{min} 이상 {max} 이하의 정수";
            Console.WriteLine($"  → {range}를 입력해야 합니다. 다음 문제로 넘어갑니다.");
            return false;
        }

